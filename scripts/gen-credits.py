#!/usr/bin/env python3
"""Regenerate CREDITS.md from apps/*/image-credits.json.

Every photo bundled in this repo is listed with its source page, author and
license. Run from the repo root:  python3 scripts/gen-credits.py
"""
import glob
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TITLES = {
    "shopline": "ShopLine", "northbank": "Northbank", "quickplate": "QuickPlate",
    "staywell": "StayWell", "homefinder": "HomeFinder", "hirehub": "HireHub",
    "careslot": "CareSlot", "ticketwave": "TicketWave", "fittrack": "FitTrack",
    "drivenow": "DriveNow",
}

out = [
    "# Credits",
    "",
    "## Photography",
    "",
    "All photographs bundled with the lab apps come from [Wikimedia Commons](https://commons.wikimedia.org/)",
    "and are released under a license that permits redistribution. Most are photos originally published",
    "on Unsplash under CC0 (public domain dedication). They are resized/cropped copies; no attribution is",
    "legally required for CC0 works, but we credit every author anyway.",
    "",
    "Generated by `scripts/gen-credits.py` from `apps/*/image-credits.json`.",
    "",
]

for path in sorted(glob.glob(os.path.join(ROOT, "apps", "*", "image-credits.json"))):
    app = os.path.basename(os.path.dirname(path))
    rows = json.load(open(path, encoding="utf-8"))
    out += [f"### {TITLES.get(app, app)}", "", "| File | Original | Author | License |", "|---|---|---|---|"]
    for r in rows:
        file = r["file"].split("/public/", 1)[-1]
        author = r["author"].replace("|", "/")
        out.append(f"| `{file}` | [{r['title']}]({r['source']}) | {author} | [{r['license']}]({r['license_url']}) |")
    out.append("")

out += [
    "## Fonts",
    "",
    "Web fonts are bundled from [Fontsource](https://fontsource.org/) npm packages and are licensed under the",
    "[SIL Open Font License 1.1](https://openfontlicense.org/).",
    "",
]

with open(os.path.join(ROOT, "CREDITS.md"), "w", encoding="utf-8", newline="\n") as f:
    f.write("\n".join(out))
print("wrote CREDITS.md")
